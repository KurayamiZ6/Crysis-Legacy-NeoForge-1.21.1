   private static final class LiveBinding<T> {
      private final Supplier<T> valueSupplier;
      private final Consumer<T> saveConsumer;
      private T lastValue;

      private LiveBinding(Supplier<T> valueSupplier, Consumer<T> saveConsumer) {
         this.valueSupplier = valueSupplier;
         this.saveConsumer = saveConsumer;
         this.lastValue = valueSupplier.get();
      }

      private void sync() {
         T currentValue = this.valueSupplier.get();
         if (!Objects.equals(currentValue, this.lastValue)) {
            this.saveConsumer.accept(currentValue);
            this.lastValue = currentValue;
         }
      }
   }
