   private static void addDoubleSlider(
      ConfigEntryBuilder entries,
      ConfigCategory category,
      String optionKey,
      String tooltipKey,
      double value,
      double defaultValue,
      double minValue,
      double maxValue,
      Consumer<Double> saveConsumer
   ) {
      int minScaled = (int)Math.round(minValue * 100.0);
      int maxScaled = (int)Math.round(maxValue * 100.0);
      int valueScaled = Mth.clamp((int)Math.round(value * 100.0), minScaled, maxScaled);
      int defaultScaled = Mth.clamp((int)Math.round(defaultValue * 100.0), minScaled, maxScaled);
      IntegerSliderEntry entry = entries.startIntSlider(tr(optionKey), valueScaled, minScaled, maxScaled)
         .setDefaultValue(defaultScaled)
         .setTooltip(new Component[]{tr(tooltipKey)})
         .setTextGetter(v -> Component.literal(String.format(Locale.ROOT, "%.2f", v.intValue() / 100.0)))
         .setSaveConsumer(v -> saveConsumer.accept(v.intValue() / 100.0))
         .build();
      category.addEntry(entry);
      registerLiveBinding(entry, v -> saveConsumer.accept(v.intValue() / 100.0));
   }

   private static <E extends Enum<E>> void addEnum(
      ConfigEntryBuilder entries,
      ConfigCategory category,
      String optionKey,
      String tooltipKey,
      Class<E> enumClass,
      E value,
      E defaultValue,
      Function<E, Component> enumNameProvider,
      Consumer<E> saveConsumer
   ) {
      EnumListEntry<E> entry = entries.startEnumSelector(tr(optionKey), enumClass, value)
         .setDefaultValue(defaultValue)
         .setEnumNameProvider(mode -> enumNameProvider.apply(enumClass.cast(mode)))
         .setTooltip(new Component[]{tr(tooltipKey)})
         .setSaveConsumer(saveConsumer)
         .build();
      category.addEntry(entry);
      registerLiveBinding(entry, saveConsumer);
   }

   private static <T> void registerLiveBinding(AbstractConfigListEntry<T> entry, Consumer<T> saveConsumer) {
      LIVE_BINDINGS.add(new NanoVisorConfigScreen.LiveBinding<>(entry::getValue, saveConsumer));
   }

