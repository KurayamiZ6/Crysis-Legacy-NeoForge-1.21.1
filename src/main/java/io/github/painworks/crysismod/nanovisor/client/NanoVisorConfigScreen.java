   private static final String I18N_ROOT = "screen.crysismod.nanovisor";
   private static final List<NanoVisorConfigScreen.LiveBinding<?>> LIVE_BINDINGS = new ArrayList<>();
   private static Screen lastBuiltConfigScreen;

   private NanoVisorConfigScreen() {
   }

   public static Screen create(Screen parent) {
      LIVE_BINDINGS.clear();
      ConfigBuilder builder = ConfigBuilder.create().setParentScreen(parent).setTitle(tr("title"));
      enableTransparentBackgroundIfSupported(builder);
      ConfigEntryBuilder entries = builder.entryBuilder();
      buildGeneral(entries, builder.getOrCreateCategory(tr("category.general")));
      ConfigCategory classic=builder.getOrCreateCategory(Component.translatable("screen.crysismod.n1theme.category"));
      classic.addEntry(entries.startColorField(Component.translatable("screen.crysismod.n1theme.color"),NanosuitClientConfig.classicInterfaceColor())
         .setDefaultValue(io.github.painworks.crysismod.nanosuit.client.ClassicHudPalette.DEFAULT)
         .setTooltip(Component.translatable("screen.crysismod.n1theme.config_help"))
         .setSaveConsumer(NanosuitClientConfig::setClassicInterfaceColor).build());
      classic.addEntry(entries.startTextDescription(Component.translatable("screen.crysismod.n1theme.config_help")).build());
      buildZoom(entries, builder.getOrCreateCategory(tr("category.zoom")));
      buildTargeting(entries, builder.getOrCreateCategory(tr("category.targeting")));
      buildNanovision(entries, builder.getOrCreateCategory(tr("category.nanovision")));
      buildHud(entries, builder.getOrCreateCategory(tr("category.hud")));
      buildTaczHud(entries, builder.getOrCreateCategory(tr("category.hud_tacz")));
      buildMinimap(entries, builder.getOrCreateCategory(tr("category.minimap")));
      buildArmorMode(entries, builder.getOrCreateCategory(tr("category.armor_mode")));
      buildNanoGeo(entries, builder.getOrCreateCategory(tr("category.nanogeo")));
      buildDebug(entries, builder.getOrCreateCategory(tr("category.debug")));
      Screen screen = builder.build();
      lastBuiltConfigScreen = screen;
      return screen;
   }

   public static boolean isNanoVisorConfigScreen(Screen screen) {
      return screen != null && screen == lastBuiltConfigScreen;
   }

   public static void applyLiveBindingsIfOpen(Screen screen) {
      if (isNanoVisorConfigScreen(screen)) {
         for (NanoVisorConfigScreen.LiveBinding<?> binding : LIVE_BINDINGS) {
            binding.sync();
         }
      }
   }

